# Regenerate tests/testthat/test-espn_offline.R from data-raw/espn_fixtures/calls.txt.
# Run from the package root after record_espn_fixtures.R:
#   Rscript data-raw/espn_fixtures/generate_tests.R

calls <- readLines(file.path("data-raw", "espn_fixtures", "calls.txt"))
calls <- trimws(sub("#.*$", "", calls))   # drop the "# keep" recording marker
blocks <- vapply(calls, function(call) {
  paste0(
    'test_that("', gsub('"', "'", call), ' parses recorded ESPN data", {\n',
    "  skip_on_cran()\n",
    "  local_espn_fixtures()\n",
    "  x <- suppressMessages(", call, ")\n",
    "  expect_espn_data(x)\n",
    "})\n"
  )
}, "")
header <- c(
  "# Generated by data-raw/espn_fixtures/generate_tests.R -- do not edit by hand.",
  "# Each call replays responses recorded by data-raw/espn_fixtures/record_espn_fixtures.R",
  "# (see helper-espn_fixtures.R), so these run offline and on CI without ESPN access.",
  ""
)
writeLines(c(header, paste(blocks, collapse = "\n")), file.path("tests", "testthat", "test-espn_offline.R"))
message(length(calls), " tests written")
