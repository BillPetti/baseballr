# Regenerate tests/testthat/test-<source>_offline.R from data-raw/http_fixtures/calls.txt,
# one file per function prefix (espn, mlb, fox, fg, ...). Run from the package root
# after record_fixtures.R:
#   Rscript data-raw/http_fixtures/generate_tests.R

calls <- readLines(file.path("data-raw", "http_fixtures", "calls.txt"))
calls <- trimws(sub("#.*$", "", calls))   # drop the "# keep" recording marker
source_of <- sub("_.*$", "", calls)

unlink(Sys.glob(file.path("tests", "testthat", "test-*_offline.R"))[
  !grepl("statcast_metrics", Sys.glob(file.path("tests", "testthat", "test-*_offline.R")))
])

for (src in unique(source_of)) {
  these <- calls[source_of == src]
  blocks <- vapply(these, function(call) {
    paste0(
      'test_that("', gsub('"', "'", call), ' parses a recorded response", {\n',
      "  skip_on_cran()\n",
      "  local_http_fixtures()\n",
      "  x <- suppressMessages(", call, ")\n",
      "  expect_recorded_data(x)\n",
      "})\n"
    )
  }, "")
  header <- c(
    "# Generated by data-raw/http_fixtures/generate_tests.R -- do not edit by hand.",
    "# Each call replays responses recorded by data-raw/http_fixtures/record_fixtures.R",
    "# (see helper-http_fixtures.R), so these run offline and on CI.",
    ""
  )
  out <- file.path("tests", "testthat", paste0("test-", src, "_offline.R"))
  writeLines(c(header, paste(blocks, collapse = "\n")), out)
  message(out, ": ", length(these), " tests")
}
